#!/usr/bin/env Rscript
suppressPackageStartupMessages(library(edgeR))
args <- commandArgs(trailingOnly=TRUE)
if (length(args) < 5) stop("Usage: edger.R counts.tsv samplesheet.csv outdir reference target")
counts <- as.matrix(read.delim(args[1], row.names=1, check.names=FALSE))
ss <- read.csv(args[2], stringsAsFactors=FALSE)
ref <- args[4]; target <- args[5]
ss <- ss[ss$condition %in% c(ref,target), c("sample","condition")]
if (!all(c(ref,target) %in% ss$condition)) stop("Both requested conditions must be present in samplesheet")
if (!all(ss$sample %in% colnames(counts))) stop("Samplesheet sample IDs must match count-matrix columns")
counts <- counts[,ss$sample,drop=FALSE]
group <- relevel(factor(ss$condition), ref=ref)
y <- DGEList(counts=counts, group=group)
keep <- filterByExpr(y, group=group)
y <- calcNormFactors(y[keep,,keep.lib.sizes=FALSE])
design <- model.matrix(~group)
y <- estimateDisp(y, design)
fit <- glmQLFit(y, design, robust=TRUE)
qlf <- glmQLFTest(fit, coef=2)
tab <- topTags(qlf, n=Inf, sort.by="PValue")$table
tab$gene_id <- rownames(tab)
fdr_cut <- as.numeric(Sys.getenv("FDR","0.05"))
lfc_cut <- as.numeric(Sys.getenv("LFC","1"))
sig <- subset(tab, FDR < fdr_cut & abs(logFC) > lfc_cut)
dir.create(args[3], recursive=TRUE, showWarnings=FALSE)
write.table(tab, file.path(args[3],"all_genes.tsv"), sep="\t", quote=FALSE, row.names=FALSE)
write.table(sig, file.path(args[3],"DEGs.tsv"), sep="\t", quote=FALSE, row.names=FALSE)
write.table(subset(sig,logFC>0), file.path(args[3],"DEGs_up.tsv"), sep="\t", quote=FALSE, row.names=FALSE)
write.table(subset(sig,logFC<0), file.path(args[3],"DEGs_down.tsv"), sep="\t", quote=FALSE, row.names=FALSE)
pdf(file.path(args[3],"edger_plots.pdf"))
plotMDS(y, labels=group)
plotBCV(y)
plotQLDisp(fit)
plotSmear(qlf, de.tags=rownames(sig)); abline(h=c(-lfc_cut,lfc_cut), col="blue")
dev.off()
